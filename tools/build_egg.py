#!/usr/bin/env python3
"""Build self-contained Pelican eggs from the reviewed source files."""

import copy
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def variable(name, env, default, description, rules, visible=True, editable=True):
    return {
        "name": name,
        "description": description,
        "env_variable": env,
        "default_value": str(default),
        "user_viewable": visible,
        "user_editable": editable,
        "rules": rules,
    }


def bundle_file(source, destination, preserve=False):
    content = (ROOT / source).read_text(encoding="utf-8")
    delimiter = "PELICAN_BUNDLE_" + destination.replace("/", "_").replace(".", "_").upper()
    assert delimiter not in content.splitlines()
    command = f"cat > '{destination}' <<'{delimiter}'\n{content.rstrip()}\n{delimiter}\n"
    if preserve:
        command = f"if [[ ! -e '{destination}' ]]; then\n{command}fi\n"
    return command


